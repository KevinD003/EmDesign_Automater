def __getattr__(name: str):
    """Keep `digitizer._PENETRATION_FLOOR_MM` live rather than a snapshot.

    `set_penetration_floor()` rebinds it inside `constants`, so re-exporting
    it eagerly would freeze the facade at the import-time value.
    """
    if name == "_PENETRATION_FLOOR_MM":
        return constants._PENETRATION_FLOOR_MM
    raise AttributeError(name)

